// Reads vendor-portal/.env (and real environment variables, which take precedence) and writes
// src/environments/env.generated.ts, whose values override those in environment.ts / environment.prod.ts.
// Runs automatically before `npm start`, `npm run build`, `npm run watch` and `npm test`.
//
//   node scripts/load-env.mjs          -> apply .env / environment variables
//   node scripts/load-env.mjs --empty  -> no overrides (used for unit tests, which expect the defaults)

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, '.env');
const outFile = resolve(root, 'src/environments/env.generated.ts');

// .env key -> environment property it overrides.
const KEYS = {
  API_BASE_URL: 'apiBaseUrl',
};

function parseEnvFile(path) {
  const values = {};
  if (!existsSync(path)) return values;
  for (const rawLine of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

const overrides = {};
if (!process.argv.includes('--empty')) {
  const fileValues = parseEnvFile(envFile);
  for (const [key, prop] of Object.entries(KEYS)) {
    const value = process.env[key] || fileValues[key];
    if (value) overrides[prop] = prop === 'apiBaseUrl' ? value.replace(/\/+$/, '') : value;
  }
}

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/load-env.mjs from .env — do not edit or commit.\n` +
    `export const envOverrides: { apiBaseUrl?: string } = ${JSON.stringify(overrides, null, 2)};\n`,
);

const summary = Object.keys(overrides).length ? JSON.stringify(overrides) : 'none';
console.log(`[load-env] environment overrides: ${summary}`);
